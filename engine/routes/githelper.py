"""Session 11: git helper. Status, diff, Haiku commit message (template when capped), commit + push."""
from __future__ import annotations

from pathlib import Path

from fastapi import APIRouter, HTTPException, Request
from pydantic import BaseModel, Field

from .. import gitops, llm
from .guide import haiku
from .projects import get_project, hub_of

router = APIRouter()

SYSTEM = """You write git commit messages for a maker's project (ESP32/Arduino firmware with PlatformIO, or an Expo/Next.js/Tauri app).

From the diff, write:
- subject: imperative mood, at most 60 characters, no trailing period, says what changed and why it matters (e.g. "Slow motors near obstacles using sonar distance").
- body: "" for small changes; otherwise up to 3 short lines starting with "- ", each one concrete change.

Files whose header says AUTO-GENERATED (pins.h, platformio.ini, theme tokens, .env.example, wiring.json) were regenerated by the hub; mention them only if they are the main change.
Describe only what the diff shows. Never invent issue numbers or names."""

SCHEMA = {
    "type": "object",
    "properties": {"subject": {"type": "string"}, "body": {"type": "string"}},
    "required": ["subject", "body"],
    "additionalProperties": False,
}


def folder(request: Request, project_id: int) -> Path:
    project = get_project(hub_of(request), project_id)
    path = Path(project["path"])
    if not path.is_dir():
        raise HTTPException(409, f"Folder {project['path']} not found. It was moved or renamed.")
    return path


def call(fn, *args, **kw):
    try:
        return fn(*args, **kw)
    except gitops.GitError as exc:
        raise HTTPException(409, str(exc)) from exc


@router.get("/projects/{project_id}/git")
def git_status(request: Request, project_id: int) -> dict:
    path = folder(request, project_id)
    st = call(gitops.status, path)
    warnings = [f"{f['path']} looks like a secret. Add it to .gitignore so it's never committed." for f in st["files"] if f["secret"]]
    return {**st, "log": call(gitops.log, path), "warnings": warnings}


@router.post("/projects/{project_id}/git/init")
def git_init(request: Request, project_id: int) -> dict:
    path = folder(request, project_id)
    if not gitops.is_repo(path):
        call(gitops.init, path)
    return git_status(request, project_id)


@router.get("/projects/{project_id}/git/diff")
def git_diff(request: Request, project_id: int, file: str) -> dict:
    return {"file": file, "diff": call(gitops.file_diff, folder(request, project_id), file)}


class MessageIn(BaseModel):
    files: list[str] | None = None


@router.post("/projects/{project_id}/git/message")
def git_message(request: Request, project_id: int, body: MessageIn) -> dict:
    """Haiku writes the message from a capped diff; the free template is the fallback."""
    hub = hub_of(request)
    path = folder(request, project_id)
    d = call(gitops.diff, path, body.files)
    if not d["files"]:
        raise HTTPException(409, "Nothing to commit. Change some files first." + (" (Secret files are never sent or committed.)" if d["skipped_secrets"] else ""))
    template = gitops.template_message(d["files"])
    listing = "\n".join(f"{f['status']}: {f['path']} (+{f['added']} -{f['removed']})" for f in d["files"])
    prompt = f"Changed files:\n{listing}\n\nDiff:\n{d['text']}"
    key = llm.cache_key("commit", prompt)
    result = haiku(hub).ask("commit_message", SYSTEM, prompt, max_tokens=600, schema=SCHEMA, effort="low", key=key)
    base = {"files": d["files"], "truncated": d["truncated"], "skipped_secrets": d["skipped_secrets"]}
    if result.status in ("sent", "cached") and isinstance(result.data, dict) and result.data.get("subject", "").strip():
        subject = result.data["subject"].strip().rstrip(".")[:72]
        text = subject + (f"\n\n{result.data['body'].strip()}" if result.data.get("body", "").strip() else "")
        return {**base, "message": text, "source": result.status, "cost_rm": round(result.cost_rm, 5), "note": ""}
    return {**base, "message": template, "source": "template", "cost_rm": 0.0, "note": (result.message or "Haiku didn't answer.") + " Used a simple template instead."}


class CommitIn(BaseModel):
    message: str = Field(min_length=3, max_length=5000)
    files: list[str] | None = None
    push: bool = False


@router.post("/projects/{project_id}/git/commit")
def git_commit(request: Request, project_id: int, body: CommitIn) -> dict:
    path = folder(request, project_id)
    sha = call(gitops.commit, path, body.message.strip(), body.files)
    pushed, push_error = False, ""
    if body.push:
        try:
            gitops.push(path)
            pushed = True
        except gitops.GitError as exc:
            push_error = str(exc)  # the commit is safe locally; say how to fix the push
    return {"commit": sha, "pushed": pushed, "push_error": push_error, **git_status(request, project_id)}


@router.post("/projects/{project_id}/git/push")
def git_push(request: Request, project_id: int) -> dict:
    path = folder(request, project_id)
    call(gitops.push, path)
    return git_status(request, project_id)
