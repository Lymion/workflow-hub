"""Release for apps: version bump, changelog from commits, icons + splash from one image, then the build.

The hub never edits the app's own files. It writes:
- release.json      (AUTO-GENERATED) version + Android versionCode
- CHANGELOG.md      (AUTO-GENERATED) entries from commit subjects
- assets/hub/*.png  (AUTO-GENERATED in a PNG text chunk) icon, adaptive icon, splash, favicon
- app.config.js     (Expo only, written once if missing; then it's yours) reads the files above
"""
from __future__ import annotations

import io
import json
import re
from datetime import date

ICONS = {"icon.png": (1024, 0.0), "adaptive-icon.png": (1024, 0.18), "splash-icon.png": (512, 0.0), "favicon.png": (48, 0.0)}
CHANGELOG_HEAD = "<!-- AUTO-GENERATED by Workflow Hub from commit messages. Edit entries in the hub's Release tab. -->\n# Changelog\n"

APP_CONFIG = """// Starter file written once by Workflow Hub. It's yours now: edit freely.
// It reads the version from release.json and the icons from assets/hub/ (both written by the hub's Release tab).
const fs = require("fs");
const release = fs.existsSync("./release.json") ? JSON.parse(fs.readFileSync("./release.json", "utf8")) : null;
const hub = (f) => (fs.existsSync(`./assets/hub/${f}`) ? `./assets/hub/${f}` : undefined);

module.exports = ({ config }) => {
  const splash = hub("splash-icon.png");
  const background = release?.background ?? "#ffffff";
  return {
    ...config,
    version: release?.version ?? config.version,
    icon: hub("icon.png") ?? config.icon,
    android: {
      ...config.android,
      versionCode: release?.versionCode ?? config.android?.versionCode,
      adaptiveIcon: hub("adaptive-icon.png") ? { foregroundImage: hub("adaptive-icon.png"), backgroundColor: background } : config.android?.adaptiveIcon,
    },
    web: { ...config.web, favicon: hub("favicon.png") ?? config.web?.favicon },
    plugins: (config.plugins ?? []).map((p) =>
      splash && Array.isArray(p) && p[0] === "expo-splash-screen" ? [p[0], { ...p[1], image: splash, backgroundColor: background }] : p,
    ),
  };
};
"""


def framework(ctx: dict) -> str | None:
    return next((s["key"] for s in ctx["stack"] if s["meta"].get("kind") == "framework"), None)


def read_release(path) -> dict:
    f = path / "release.json"
    if f.is_file():
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
            return {"version": str(data.get("version", "0.1.0")), "versionCode": int(data.get("versionCode", 1)), "background": data.get("background", "#ffffff")}
        except (json.JSONDecodeError, ValueError):
            pass
    version = "0.1.0"
    pkg = path / "package.json"
    if pkg.is_file():
        try:
            version = json.loads(pkg.read_text(encoding="utf-8")).get("version") or version
        except json.JSONDecodeError:
            pass
    return {"version": version, "versionCode": 0, "background": "#ffffff"}


def bump(version: str, kind: str) -> str:
    m = re.match(r"^(\d+)\.(\d+)\.(\d+)", version)
    major, minor, patch = (int(x) for x in m.groups()) if m else (0, 1, 0)
    if kind == "major":
        return f"{major + 1}.0.0"
    if kind == "minor":
        return f"{major}.{minor + 1}.0"
    return f"{major}.{minor}.{patch + 1}"


GROUPS = [("Added", re.compile(r"^(add|create|new|introduce|support)\b", re.I)), ("Fixed", re.compile(r"^(fix|repair|correct|resolve|stop)\b", re.I))]


def changelog_draft(subjects: list[str]) -> str:
    groups: dict[str, list[str]] = {"Added": [], "Fixed": [], "Changed": []}
    for s in subjects:
        if s.startswith(("Release v", "Merge ")) or s == "Set up with Workflow Hub":
            continue
        name = next((g for g, rx in GROUPS if rx.search(s)), "Changed")
        groups[name].append(s)
    return "\n".join(f"### {g}\n" + "\n".join(f"- {x}" for x in items) + "\n" for g, items in groups.items() if items).strip()


def render_release_json(rel: dict) -> str:
    return json.dumps({"_comment": "AUTO-GENERATED by Workflow Hub. Change the version in the hub's Release tab.", **rel}, indent=2) + "\n"


def render_changelog(existing: str, version: str, notes: str) -> str:
    body = existing.split("# Changelog\n", 1)[1] if "# Changelog\n" in existing else ""
    entry = f"\n## {version} ({date.today().isoformat()})\n\n{notes.strip() or '- Small fixes and improvements'}\n"
    return CHANGELOG_HEAD + entry + body


def make_icons(image_bytes: bytes, background: str) -> dict[str, bytes]:
    """One square-ish image in, PNGs out. Each PNG carries an AUTO-GENERATED text chunk."""
    from PIL import Image, PngImagePlugin

    src = Image.open(io.BytesIO(image_bytes)).convert("RGBA")
    side = min(src.size)
    left, top = (src.width - side) // 2, (src.height - side) // 2
    src = src.crop((left, top, left + side, top + side))
    out = {}
    for name, (size, pad) in ICONS.items():
        canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0) if name != "icon.png" else background)
        inner = int(size * (1 - 2 * pad))
        img = src.resize((inner, inner), Image.LANCZOS)
        canvas.alpha_composite(img, ((size - inner) // 2, (size - inner) // 2))
        info = PngImagePlugin.PngInfo()
        info.add_text("Comment", "AUTO-GENERATED by Workflow Hub from one image in the Release tab.")
        buf = io.BytesIO()
        canvas.save(buf, "PNG", pnginfo=info, optimize=True)
        out[name] = buf.getvalue()
    return out


def png_is_owned(path) -> bool:
    if not path.exists():
        return True
    try:
        from PIL import Image

        with Image.open(path) as im:
            return "AUTO-GENERATED" in str(im.info.get("Comment", ""))
    except Exception:
        return False
