"""App wizard: scaffold, install, theme file from design tokens, .env.example, CLAUDE.md, git, GitHub.

Fast steps (files) run in setup(); slow steps (scaffold, npm install, gh repo create) run in
background() so Create project returns at once. The hub never edits the app's own code: the
theme file and .env.example are AUTO-GENERATED; screens are new files written once.
"""
from __future__ import annotations

import json
import re

STATUS_FILES = ["package.json", "design-tokens.json", "src/theme/tokens.ts", ".env.example", "CLAUDE.md"]

DEFAULT_TOKENS = {
    "colors": {
        "light": {"primary": "#0071E3", "background": "#FFFFFF", "surface": "#F2F2F7", "text": "#1D1D1F", "muted": "#5E5E66", "success": "#1E7B34", "warning": "#9A5B00", "danger": "#C8001A"},
        "dark": {"primary": "#0A84FF", "background": "#000000", "surface": "#1C1C1E", "text": "#F5F5F7", "muted": "#AEAEB5", "success": "#30D158", "warning": "#FF9F0A", "danger": "#FF453A"},
    },
    "fonts": {"body": "System", "heading": "System", "mono": "Menlo"},
    "spacing": [0, 4, 8, 12, 16, 24, 32, 48],
    "radius": {"sm": 8, "md": 12, "lg": 16},
}


def status_files(ctx: dict) -> list[str]:
    return ["package.json", "design-tokens.json", theme_target(ctx)[0], ".env.example", "CLAUDE.md"]


def framework(ctx: dict) -> dict | None:
    return next((s for s in ctx["stack"] if s["meta"].get("kind") == "framework"), None)


def theme_target(ctx: dict) -> tuple[str, str]:
    fw = framework(ctx)
    if fw and fw["key"] in ("nextjs", "tauri"):
        return "src/styles/tokens.css", "css"
    return "src/theme/tokens.ts", "ts"


# ---------- renderers ----------

def read_tokens(path) -> dict:
    f = path / "design-tokens.json"
    if f.is_file():
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
            return {k: data.get(k, v) for k, v in DEFAULT_TOKENS.items()}
        except json.JSONDecodeError:
            pass
    return json.loads(json.dumps(DEFAULT_TOKENS))


def render_tokens_json(tokens: dict) -> str:
    return json.dumps({"_comment": "AUTO-GENERATED by Workflow Hub. Edit tokens in the hub's Design tokens tab.", **tokens}, indent=2) + "\n"


def render_theme_ts(tokens: dict) -> str:
    def obj(d: dict, indent: str = "  ") -> str:
        return "{\n" + "".join(f"{indent}  {k}: {json.dumps(v)},\n" for k, v in d.items()) + indent + "}"

    c = tokens["colors"]
    return (
        "// AUTO-GENERATED by Workflow Hub from design-tokens.json. Do not edit: change tokens in the hub.\n"
        "export const colors = {\n"
        f"  light: {obj(c['light'])},\n"
        f"  dark: {obj(c['dark'])},\n"
        "} as const;\n\n"
        f"export const fonts = {obj(tokens['fonts'], '')} as const;\n\n"
        f"export const spacing = {json.dumps(tokens['spacing'])} as const;\n\n"
        f"export const radius = {obj(tokens['radius'], '')} as const;\n\n"
        "export type ColorName = keyof typeof colors.light;\n"
    )


def render_theme_css(tokens: dict) -> str:
    def block(sel: str, colors: dict) -> str:
        return sel + " {\n" + "".join(f"  --color-{k}: {v};\n" for k, v in colors.items()) + "}\n"

    extra = "".join(f"  --space-{i}: {v}px;\n" for i, v in enumerate(tokens["spacing"])) + "".join(f"  --radius-{k}: {v}px;\n" for k, v in tokens["radius"].items())
    fonts = "".join(f"  --font-{k}: {v if v != 'System' else 'system-ui, -apple-system, sans-serif'};\n" for k, v in tokens["fonts"].items())
    return (
        "/* AUTO-GENERATED by Workflow Hub from design-tokens.json. Do not edit: change tokens in the hub. */\n"
        + block(":root", tokens["colors"]["light"]).replace("}\n", extra + fonts + "}\n")
        + "@media (prefers-color-scheme: dark) {\n" + block("  :root", tokens["colors"]["dark"]).replace("\n  --", "\n    --").replace("\n}", "\n  }") + "}\n"
    )


def render_env_example(ctx: dict) -> str:
    keys = []
    for s in ctx["stack"]:
        for k in s["meta"].get("env", []) or []:
            if k not in keys:
                keys.append(k)
    lines = ["# AUTO-GENERATED by Workflow Hub from the project stack. Copy to .env and fill in. Never commit .env."]
    lines += [f"{k}=" for k in keys] or ["# No environment variables needed yet."]
    return "\n".join(lines) + "\n"


def render_claude_md(ctx: dict) -> str:
    p = ctx["project"]
    names = ", ".join(s["title"] for s in ctx["stack"]) or "no stack yet"
    theme, _ = theme_target(ctx)
    return f"""# {p['name']}

App project ({names}). Set up by Workflow Hub.

- `{theme}`, `design-tokens.json` and `.env.example` are AUTO-GENERATED by the hub. Don't edit them; change tokens in the hub.
- Use the theme tokens for every colour, font, spacing and radius; no hard-coded hex values.
- Secrets live in `.env` (git-ignored). Only `EXPO_PUBLIC_` variables reach an Expo app.
"""


