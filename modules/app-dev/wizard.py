PRETTIER = '{\n  "singleQuote": false,\n  "semi": true,\n  "printWidth": 100,\n  "trailingComma": "all"\n}\n'


def screen_file(ctx: dict, name: str) -> tuple[str, str]:
    """A new screen as its own file. Expo Router / Next.js route from files, so no other file changes."""
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-") or "screen"
    comp = "".join(w.capitalize() for w in slug.split("-")) + "Screen"
    fw = framework(ctx)
    if fw and fw["key"] == "nextjs":
        return f"src/app/{slug}/page.tsx", f'export default function {comp}() {{\n  return (\n    <main style={{{{ padding: "var(--space-4)", color: "var(--color-text)" }}}}>\n      <h1>{name}</h1>\n    </main>\n  );\n}}\n'
    return f"app/{slug}.tsx", (
        'import { View, Text, StyleSheet, useColorScheme } from "react-native";\n'
        'import { colors, spacing } from "../src/theme/tokens";\n\n'
        f"export default function {comp}() {{\n"
        '  const c = colors[useColorScheme() === "dark" ? "dark" : "light"];\n'
        "  return (\n"
        "    <View style={[styles.wrap, { backgroundColor: c.background }]}>\n"
        f'      <Text style={{[styles.title, {{ color: c.text }}]}}>{name}</Text>\n'
        "    </View>\n"
        "  );\n"
        "}\n\n"
        "const styles = StyleSheet.create({\n"
        "  wrap: { flex: 1, padding: spacing[4] },\n"
        '  title: { fontSize: 28, fontWeight: "700" },\n'
        "});\n"
    )


def save_tokens(ctx: dict, tokens: dict) -> dict:
    """Write design-tokens.json and regenerate the theme file. Returns file statuses + the theme text."""
    path = ctx["path"]
    theme_rel, kind = theme_target(ctx)
    theme = render_theme_ts(tokens) if kind == "ts" else render_theme_css(tokens)
    files = [
        {"file": "design-tokens.json", "status": ctx["write_owned"](path / "design-tokens.json", render_tokens_json(tokens))},
        {"file": theme_rel, "status": ctx["write_owned"](path / theme_rel, theme)},
    ]
    return {"files": files, "theme_file": theme_rel, "theme": theme}


# ---------- setup ----------

def setup_check(ctx: dict) -> list[dict]:
    which = ctx["which"]
    items = [
        {"id": "node", "label": "Node.js", "ok": bool(which("node")), "fix": "Install Node.js LTS: winget install OpenJS.NodeJS.LTS"},
        {"id": "git", "label": "Git", "ok": bool(which("git")), "fix": "Install Git from git-scm.com."},
        {"id": "gh", "label": "GitHub CLI", "ok": bool(which("gh")), "fix": "Install from cli.github.com, then run: gh auth login"},
    ]
    fw = framework(ctx)
    if fw and fw["key"] == "tauri":
        items.append({"id": "rust", "label": "Rust", "ok": bool(which("cargo")), "fix": "Install Rust: winget install Rustlang.Rustup"})
    if fw and fw["key"] == "expo":
        items.append({"id": "expo-go", "label": "Expo Go on your phone", "ok": None, "fix": "Install Expo Go from the Play Store or App Store to preview the app."})
    for i in items:
        if i["ok"]:
            i["fix"] = ""
    return items


def findings(ctx: dict) -> list[dict]:
    return ctx["checks"].run_stack(ctx["stack"]) if ctx.get("checks") else []


def setup(ctx: dict) -> dict:
    path = ctx["path"]
    tokens = read_tokens(path)
    theme_rel, kind = theme_target(ctx)
    report = []

    def owned(rel: str, content: str):
        report.append({"file": rel, "status": ctx["write_owned"](path / rel, content)})

    def once(rel: str, content: str):
        report.append({"file": rel, "status": ctx["write_once"](path / rel, content)})

    owned("design-tokens.json", render_tokens_json(tokens))
    owned(theme_rel, render_theme_ts(tokens) if kind == "ts" else render_theme_css(tokens))
    owned(".env.example", render_env_example(ctx))
    once("CLAUDE.md", render_claude_md(ctx))
    once(".prettierrc", PRETTIER)
    once(".gitignore", GITIGNORE)
    return {"files": report, "steps": []}


SCAFFOLD_DIR = ".hub-scaffold"


def scaffold(ctx: dict, fw: dict) -> dict:
    """Run the framework's create command in a temp folder, then move its files in without
    overwriting anything already in the project (create-* tools refuse non-empty folders)."""
    import shutil

    log, run, which, path = ctx["log"], ctx["run"], ctx["which"], ctx["path"]
    name = ctx["project"]["slug"]
    cmd = (fw["meta"].get("scaffold") or "").replace("{name}", name)
    if not cmd:
        return {"step": "scaffold", "ok": False, "note": f"{fw['title']} has no scaffold command in its handbook chapter."}
    manual = f"Run it yourself in the folder's parent: {cmd}"
    log(f"$ {cmd}")
    parts = cmd.split()
    exe = which(parts[0])
    tmp = path / SCAFFOLD_DIR
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)
    try:
        ok = exe is not None and run([exe, *parts[1:]], cwd=tmp, timeout=900) is not None
        made = tmp / name
        if ok and made.is_dir():
            for item in made.iterdir():
                dest = path / item.name
                if dest.exists():
                    log(f"kept your {item.name}")
                    continue
                shutil.move(str(item), str(dest))
        ok = ok and (path / "package.json").exists()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    log("scaffold done" if ok else "scaffold failed")
    return {"step": "scaffold", "ok": ok, "note": "" if ok else manual}


def background(ctx: dict) -> dict:
    """Slow steps: scaffold the framework, install stack packages, git, GitHub. Runs in a job."""
    log, run, which, path = ctx["log"], ctx["run"], ctx["which"], ctx["path"]
    steps = []
    fw = framework(ctx)
    if ctx.get("run_scaffold") and fw and not (path / "package.json").exists():
        steps.append(scaffold(ctx, fw))
    if ctx.get("run_install") and (path / "package.json").exists():
        pkgs = []
        for s in ctx["stack"]:
            if s["meta"].get("kind") == "framework":
                continue
            pkgs += [p for p in s["meta"].get("packages", []) or [] if p not in pkgs]
        if pkgs:
            log("$ npm install " + " ".join(pkgs))
            npm = which("npm")
            ok = npm is not None and run([npm, "install", *pkgs], cwd=path, timeout=600) is not None
            steps.append({"step": "npm install", "ok": ok, "note": "" if ok else "Run: npm install " + " ".join(pkgs)})
    # the theme file again, in case the scaffold created src/ after setup()
    setup(ctx)
    if ctx.get("run_git") and which("git") and not (path / ".git").exists():
        ok = run([which("git"), "init", "-b", "main"], cwd=path) is not None
        run([which("git"), "add", "-A"], cwd=path)
        run([which("git"), "commit", "-m", "Set up with Workflow Hub"], cwd=path)
        steps.append({"step": "git init", "ok": ok})
        log("git init done")
    if ctx.get("run_github") and which("gh"):
        name = ctx["project"]["slug"]
        out = run([which("gh"), "repo", "create", name, "--private", "--source=.", "--push"], cwd=path, timeout=120)
        steps.append({"step": "gh repo create", "ok": out is not None, "note": "" if out is not None else "Run: gh auth login, then try again."})
        log("GitHub repo created" if out is not None else "gh repo create failed")
    return {"steps": steps}


def checklist(ctx: dict, findings_list: list[dict], items: list[dict]) -> list[str]:
    tasks = [f"Install: {i['label']}" for i in items if i["ok"] is False]
    fw = framework(ctx)
    if fw and fw["key"] == "expo":
        tasks.append("Run npx expo start and scan the QR code with Expo Go")
    elif fw:
        tasks.append("Run npm run dev and open the app")
    if any(s["meta"].get("env") for s in ctx["stack"]):
        tasks.append("Copy .env.example to .env and fill in the keys")
    tasks += [f"{f['part']}: {f['fix']}" for f in findings_list if f["level"] in ("bad", "warn")]
    return tasks
