"""Robotics wizard: wiring, platformio.ini, pins.h, main.cpp, PARTS.md, setup checks.

All plain code. The engine passes in a context with helpers:
  ctx = {project, board, parts, wiring, root, path, suggest, write_owned, write_once, which, run, findings}
"""
from __future__ import annotations

import json
import re
from datetime import date

GPIO_MODES = {"OUTPUT", "PWM", "INPUT", "INPUT_PULLUP", "ANALOG", "I2C"}
NEEDS_BOARD = True
STATUS_FILES = ["platformio.ini", "include/pins.h", "wiring.json", "PARTS.md", "src/main.cpp"]


# ---------- names ----------

def camel(text: str) -> str:
    words = re.split(r"[^a-zA-Z0-9]+", text)
    words = [w for w in words if w]
    return words[0].lower() + "".join(w[:1].upper() + w[1:].lower() for w in words[1:]) if words else "signal"


def macro(signal: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", signal).upper()


def signal_name(meta: dict, part_key: str, pin: str, instance: int, qty: int) -> str:
    base = (meta.get("signals") or {}).get(pin) or camel(f"{part_key} {pin}")
    return f"{base}{instance}" if qty > 1 else base


# ---------- wiring ----------

def sync_wiring(board: dict, parts: list[dict], wiring: dict, suggest) -> dict:
    """Keep existing wires, drop wires for removed parts, give new part pins a suitable free pin."""
    same_board = wiring.get("board") == board["board"]
    keep = []
    instances = {(p["key"], i) for p in parts for i in range(1, int(p["qty"]) + 1)}
    for w in wiring.get("wires", []) if same_board else []:
        if (w["part"], int(w.get("instance", 1))) in instances:
            keep.append(w)
    have = {(w["part"], int(w.get("instance", 1)), w["partPin"]) for w in keep}
    used = {str(w["boardPin"]) for w in keep if w.get("boardPin") not in (None, "") and w.get("mode") != "I2C"}
    i2c = board.get("i2c", {})
    has_divider = any(p["key"] == "resistor-kit" for p in parts)
    logic = float(board.get("logic_voltage", 3.3))
    for p in parts:
        meta = p["meta"]
        for inst in range(1, int(p["qty"]) + 1):
            for pin in meta.get("pins", []):
                mode = str(pin.get("mode", "")).upper()
                if mode not in GPIO_MODES or pin.get("optional") or (p["key"], inst, pin["name"]) in have:
                    continue
                if mode == "I2C":
                    gpio = i2c.get("sda") if pin["name"].upper() == "SDA" else i2c.get("scl")
                else:
                    gpio = suggest(board, "PWM" if mode == "PWM" else ("ANALOG" if mode == "ANALOG" else ("INPUT" if mode.startswith("INPUT") else "OUTPUT")), used)
                    if gpio:
                        used.add(str(gpio))
                five_in = mode.startswith("INPUT") and str(pin.get("voltage", "")).startswith("5") and logic < 4.5
                keep.append({
                    "part": p["key"], "instance": inst, "partPin": pin["name"], "boardPin": gpio,
                    "signalName": signal_name(meta, p["key"], pin["name"], inst, int(p["qty"])), "mode": mode,
                    "divider": bool(five_in and has_divider),
                })
    order = {p["key"]: i for i, p in enumerate(parts)}
    keep.sort(key=lambda w: (order.get(w["part"], 99), int(w.get("instance", 1))))
    return {"_comment": "AUTO-GENERATED by Workflow Hub. Edit wires in the hub's Wiring tab.", "board": board["board"], "parts": [{"key": p["key"], "qty": int(p["qty"])} for p in parts], "wires": keep}


# ---------- renderers ----------

def render_pins_h(board: dict, wiring: dict, titles: dict) -> str:
    lines = [
        "// AUTO-GENERATED by Workflow Hub from wiring.json. Do not edit: change wires in the hub.",
        "#pragma once",
        "",
        f"// Board: {board['name']} ({board['pio_board']}), {board.get('logic_voltage', 3.3):g}V logic",
    ]
    width = max([len(macro(w["signalName"])) for w in wiring["wires"]] + [12])
    for w in wiring["wires"]:
        if w.get("boardPin") in (None, ""):
            lines.append(f"// {macro(w['signalName'])}: not connected yet ({titles.get(w['part'], w['part'])} {w['partPin']})")
            continue
        note = f"{titles.get(w['part'], w['part'])} {w['partPin']}" + ("  (via 1k/2k divider)" if w.get("divider") else "")
        lines.append(f"#define {macro(w['signalName']).ljust(width)} {w['boardPin']:<4} // {note}")
    return "\n".join(lines) + "\n"


def render_platformio(board: dict, parts: list[dict]) -> str:
    libs = []
    for p in parts:
        dep = p["meta"].get("lib_dep")
        if isinstance(dep, dict):
            dep = dep.get(board["platform"])
        if dep and dep not in libs:
            libs.append(dep)
    lines = [
        "; AUTO-GENERATED by Workflow Hub from the project cart. Do not edit: change parts in the hub.",
        "; Your own settings go in platformio.local.ini (kept between regenerations).",
        "",
        "[platformio]",
        f"default_envs = {board['pio_board']}",
        "extra_configs = platformio.local.ini",
        "",
        f"[env:{board['pio_board']}]",
        f"platform = {board['platform']}",
        f"board = {board['pio_board']}",
        f"framework = {board.get('framework', 'arduino')}",
        f"monitor_speed = {board.get('monitor_speed', 115200)}",
    ]
    if board.get("build_flags"):
        lines.append("build_flags =")
        lines += [f"    {f}" for f in board["build_flags"]]
    if libs:
        lines.append("lib_deps =")
        lines += [f"    {lib}" for lib in libs]
    return "\n".join(lines) + "\n"


def render_main_cpp(project: dict, board: dict, parts: list[dict], wiring: dict) -> str:
    setup_lines, starters, uses_i2c = [], [], False
    for w in wiring["wires"]:
        if w.get("boardPin") in (None, ""):
            continue
        m = macro(w["signalName"])
        if w["mode"] in ("OUTPUT", "PWM"):
            setup_lines.append(f"  pinMode({m}, OUTPUT);")
        elif w["mode"] == "INPUT":
            setup_lines.append(f"  pinMode({m}, INPUT);")
        elif w["mode"] == "INPUT_PULLUP":
            setup_lines.append(f"  pinMode({m}, INPUT_PULLUP);")
        elif w["mode"] == "I2C":
            uses_i2c = True
    for p in parts:
        snip = p["meta"].get("snippet")
        if snip:
            starters.append(f"// {p['title']}: starter code in the hub's snippet library ({snip}).")
    if uses_i2c:
        setup_lines.append("  Wire.begin();  // I2C on the board's default SDA/SCL pins")
    body = "\n".join(setup_lines) or "  // No pins wired yet. Add parts in the hub, then re-run setup."
    return f"""// Generated once by Workflow Hub for {project['name']}. This file is yours: the hub never changes it again.
// Pin names come from include/pins.h (auto-generated from the hub's wiring view).
#include <Arduino.h>
{"#include <Wire.h>" + chr(10) if uses_i2c else ""}#include "pins.h"

void setupPins() {{
{body}
}}

{chr(10).join(starters) if starters else "// Part starter code lives in the hub's snippet library."}

void setup() {{
  Serial.begin({board.get('monitor_speed', 115200)});
  setupPins();
  Serial.println("{project['name']} ready");
}}

unsigned long lastTick = 0;
const unsigned long TICK_MS = 1000;

void loop() {{
  // Non-blocking loop: never use delay(), check millis() instead.
  if (millis() - lastTick >= TICK_MS) {{
    lastTick = millis();
    Serial.println(millis());
  }}
}}
"""


STATUS = {"need": "Need", "ordered": "Ordered", "have": "In hand"}


def render_parts_md(project: dict, board: dict, parts: list[dict], wiring: dict) -> str:
    rows, total, to_buy = [], 0.0, 0.0
    for p in parts:
        lo = (p["meta"].get("price_rm") or [0])[0]
        cost = float(lo) * int(p["qty"])
        total += cost
        if p.get("status", "need") == "need":
            to_buy += cost
        rows.append(f"| {p['title']} | {p['qty']} | {STATUS.get(p.get('status', 'need'), 'Need')} | RM{cost:g} |")
    pins = [f"| `{macro(w['signalName'])}` | {w['part']} {w['partPin']} | {w.get('boardPin') or '—'} |" for w in wiring["wires"]]
    return (
        f"<!-- AUTO-GENERATED by Workflow Hub. Do not edit: change parts in the hub. -->\n# {project['name']}: parts\n\n"
        f"Board: **{board['name']}** · updated {date.today().isoformat()}\n\n"
        "| Part | Qty | Status | Price |\n|---|---|---|---|\n" + "\n".join(rows) + f"\n| **Total** | | RM{to_buy:g} to buy | **RM{total:g}** |\n\n"
        "## Pins\n\n| Signal | Part pin | Board pin |\n|---|---|---|\n" + "\n".join(pins) + "\n"
    )


def render_claude_md(project: dict, board: dict) -> str:
    return f"""# {project['name']}

Robotics project on {board['name']} with PlatformIO. Set up by Workflow Hub.

- `include/pins.h`, `platformio.ini`, `wiring.json` and `PARTS.md` are AUTO-GENERATED by the hub. Don't edit them; change parts and wires in the hub.
- Your code lives in `src/`. Use the pin names from `pins.h`, never raw numbers.
- Keep `loop()` non-blocking (`millis()`, no `delay()`).
- Extra PlatformIO settings go in `platformio.local.ini`.
"""


