# ---------- setup ----------

def setup_check(ctx: dict) -> list[dict]:
    which, run = ctx["which"], ctx["run"]
    items = []
    code = which("code")
    items.append({"id": "vscode", "label": "VS Code", "ok": bool(code), "fix": "" if code else "Install VS Code from code.visualstudio.com and tick 'Add to PATH'."})
    ext_ok = False
    if code:
        out = run([code, "--list-extensions"], timeout=20)
        ext_ok = "platformio.platformio-ide" in (out or "").lower()
    items.append({"id": "platformio-ext", "label": "PlatformIO extension", "ok": ext_ok, "fix": "" if ext_ok else "Run: code --install-extension platformio.platformio-ide"})
    pio = which("pio") or which("platformio")
    items.append({"id": "pio", "label": "PlatformIO CLI", "ok": bool(pio), "fix": "" if pio else "Comes with the PlatformIO extension; or run: pip install platformio"})
    git = which("git")
    items.append({"id": "git", "label": "Git", "ok": bool(git), "fix": "" if git else "Install Git from git-scm.com."})
    if ctx["board"].get("platform") == "espressif32":
        items.append({"id": "driver", "label": "USB driver (CP210x / CH340)", "ok": None, "fix": "If no COM port appears when you plug the board in, install the CP210x driver (Silicon Labs) or CH340 driver."})
    return items


def setup(ctx: dict) -> dict:
    project, board, parts, path = ctx["project"], ctx["board"], ctx["parts"], ctx["path"]
    wiring = sync_wiring(board, parts, ctx.get("wiring") or {}, ctx["suggest"])
    titles = {p["key"]: p["title"] for p in parts}
    report = []

    def owned(rel: str, content: str):
        report.append({"file": rel, "status": ctx["write_owned"](path / rel, content)})

    def once(rel: str, content: str):
        report.append({"file": rel, "status": ctx["write_once"](path / rel, content)})

    owned("wiring.json", json.dumps(wiring, indent=2) + "\n")
    owned("include/pins.h", render_pins_h(board, wiring, titles))
    owned("platformio.ini", render_platformio(board, parts))
    owned("PARTS.md", render_parts_md(project, board, parts, wiring))
    once("src/main.cpp", render_main_cpp(project, board, parts, wiring))
    once("platformio.local.ini", "; Your own PlatformIO settings. The hub never changes this file.\n")
    once("CLAUDE.md", render_claude_md(project, board))
    once(".gitignore", GITIGNORE)
    for d in ("lib", "test"):
        (path / d).mkdir(exist_ok=True)

    steps = []
    if ctx.get("run_pio"):
        pio = ctx["which"]("pio") or ctx["which"]("platformio")
        if pio:
            out = ctx["run"]([pio, "project", "init", "--ide", "vscode"], cwd=path, timeout=180)
            steps.append({"step": "pio project init --ide vscode", "ok": out is not None})
        else:
            steps.append({"step": "pio project init", "ok": None, "note": "PlatformIO CLI not found; VS Code's PlatformIO extension finishes setup when you open the folder."})
    if ctx.get("run_git"):
        git = ctx["which"]("git")
        if git and not (path / ".git").exists():
            ok = ctx["run"]([git, "init"], cwd=path) is not None
            committed = ok and ctx["run"]([git, "add", "-A"], cwd=path) is not None and ctx["run"]([git, "commit", "-m", "Set up with Workflow Hub"], cwd=path) is not None
            steps.append({"step": "git init", "ok": ok, "note": "" if committed else "Repository created; first commit skipped (set git user.name and user.email)."})
    return {"files": report, "steps": steps, "wiring": wiring}


def checklist(ctx: dict, findings: list[dict], check_items: list[dict]) -> list[str]:
    """Setup checklist tasks for the project page."""
    tasks = [f"Install: {i['label']}" for i in check_items if i["ok"] is False]
    tasks.append("Open in VS Code and build (PlatformIO: Build)")
    tasks.append("Upload the starter and open the serial monitor")
    tasks += [f"{f['part']}: {f['fix']}" for f in findings if f["level"] in ("bad", "warn")]
    return tasks
